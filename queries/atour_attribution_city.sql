WITH base AS (
  SELECT EXTRACT(YEAR FROM IN_DATE) AS yr,
         CASE WHEN EXTRACT(MONTH FROM IN_DATE) <= 6 THEN 'H1' ELSE 'H2' END AS half,
         CITY_NAME AS city, ROOM_NIGHTS
  FROM hotel_order
  WHERE SUPPLIER_NO='亚朵'
    AND STATUS IN ('已离店','已确认')
    AND ROOM_NIGHTS > 0
    AND booking_name NOT LIKE '%测试%'
    AND hotel_name NOT LIKE '%测试%'
)
SELECT COALESCE(NULLIF(city,''),'未知') AS city,
       SUM(CASE WHEN yr=2025 AND half='H1' THEN ROOM_NIGHTS END) AS h1_2025,
       SUM(CASE WHEN yr=2026 AND half='H1' THEN ROOM_NIGHTS END) AS h1_2026
FROM base GROUP BY 1
HAVING SUM(CASE WHEN yr=2026 AND half='H1' THEN ROOM_NIGHTS END) IS NOT NULL
   OR SUM(CASE WHEN yr=2025 AND half='H1' THEN ROOM_NIGHTS END) IS NOT NULL
ORDER BY h1_2026 DESC LIMIT 25;
