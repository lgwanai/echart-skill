WITH base AS (
  SELECT EXTRACT(YEAR FROM IN_DATE) AS yr,
         CASE WHEN EXTRACT(MONTH FROM IN_DATE)<=6 THEN 'H1' END AS half,
         CITY_NAME AS city, ROOM_NIGHTS
  FROM hotel_order
  WHERE SUPPLIER_NO='亚朵' AND STATUS IN ('已离店','已确认') AND ROOM_NIGHTS>0
    AND booking_name NOT LIKE '%测试%' AND hotel_name NOT LIKE '%测试%'
    AND EXTRACT(MONTH FROM IN_DATE)<=6
),
p AS (SELECT COALESCE(NULLIF(city,''),'未知') city,
      SUM(CASE WHEN yr=2024 THEN ROOM_NIGHTS END) rn_2024,
      SUM(CASE WHEN yr=2025 THEN ROOM_NIGHTS END) rn_2025,
      SUM(CASE WHEN yr=2026 THEN ROOM_NIGHTS END) rn_2026
      FROM base GROUP BY 1)
SELECT city, rn_2024, rn_2025, rn_2026,
       rn_2026 - rn_2025 AS d_2625,
       rn_2025 - rn_2024 AS d_2524
FROM p
WHERE rn_2026 IS NOT NULL AND rn_2025 IS NOT NULL
ORDER BY d_2625 ASC LIMIT 15;
