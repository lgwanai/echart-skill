WITH base AS (
  SELECT EXTRACT(YEAR FROM IN_DATE) AS yr, EXTRACT(MONTH FROM IN_DATE) AS mon, ROOM_NIGHTS
  FROM hotel_order
  WHERE SUPPLIER_NO='亚朵' AND STATUS IN ('已离店','已确认') AND ROOM_NIGHTS>0
    AND booking_name NOT LIKE '%测试%' AND hotel_name NOT LIKE '%测试%'
    AND EXTRACT(MONTH FROM IN_DATE)<=6
),
p AS (SELECT mon,
      COALESCE(SUM(CASE WHEN yr=2025 THEN ROOM_NIGHTS END),0) rn25,
      COALESCE(SUM(CASE WHEN yr=2026 THEN ROOM_NIGHTS END),0) rn26
      FROM base GROUP BY 1)
SELECT mon, rn25, rn26, rn26-rn25 AS delta FROM p ORDER BY mon;
